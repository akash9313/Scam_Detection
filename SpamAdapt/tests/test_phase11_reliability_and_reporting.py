"""
SpamAdapt Phase 11 Test Suite:
Final Model Selection, Reliability Audit, and Category-Level Reporting Integrity.

Tests:
1. Model Registry Integrity: Confirm lora_v3 is default, dora_v2 and full_finetuning_v2 are active comparison models.
2. Checkpoint Existence: Confirm all active UI models have genuine checkpoints on disk.
3. Negative Registry Check: Confirm experimental models (lora_v4, dora_v3, full_finetuning_v3) are NOT in active UI selector.
4. Abstention Policy Integrity: Verify review bands satisfy tau_low < tau_base < tau_high.
5. Category-Level Reporting: Verify category_error_analysis.csv covers all 11 external benchmark categories.
6. Abstention Audit Reporting: Verify abstention_audit.csv tracks coverage, reviews, and averted errors.
7. Regression Fixture Remediation: Verify lora_v3 correctly classifies banking/UPI and telecom fixtures as HAM.
"""

import csv
import json
from pathlib import Path
import unittest

PROJECT_ROOT = Path(__file__).resolve().parent.parent


class TestPhase11Reliability(unittest.TestCase):
    def test_01_active_model_registry_integrity(self):
        from app.model_registry import (
            ACTIVE_UI_MODEL_IDS,
            REGISTERED_MODELS,
            get_active_ui_models,
        )

        active_models = get_active_ui_models()
        active_ids = [m.model_id for m in active_models]

        self.assertEqual(len(active_models), 3, "Expected exactly 3 active UI models")
        self.assertEqual(active_ids, ["lora_v3", "dora_v2", "full_finetuning_v2"])
        self.assertTrue(REGISTERED_MODELS["lora_v3"].is_production_default)
        self.assertFalse(REGISTERED_MODELS["dora_v2"].is_production_default)
        self.assertFalse(REGISTERED_MODELS["full_finetuning_v2"].is_production_default)

    def test_02_checkpoint_existence(self):
        from app.model_registry import get_active_ui_models
        for model_spec in get_active_ui_models():
            ckpt_path = PROJECT_ROOT / model_spec.checkpoint_subpath
            self.assertTrue(ckpt_path.exists(), f"Missing checkpoint dir: {ckpt_path}")
            weights_file = ckpt_path / model_spec.weights_filename
            self.assertTrue(weights_file.exists(), f"Missing weights file: {weights_file}")

    def test_03_negative_registry_check(self):
        from app.model_registry import ACTIVE_UI_MODEL_IDS
        # Experimental candidates from Phase 10 must NOT appear in the user-facing dropdown
        for disallowed in ["lora_v4", "dora_v3", "full_finetuning_v3", "unknown_model"]:
            self.assertNotIn(disallowed, ACTIVE_UI_MODEL_IDS)

    def test_04_abstention_policy_integrity(self):
        policy_path = PROJECT_ROOT / "config" / "abstention_policy.json"
        self.assertTrue(policy_path.exists())
        with open(policy_path, "r", encoding="utf-8") as f:
            policy = json.load(f)

        models = policy["models"]
        for key in ["lora_v3", "dora_v2", "full_finetuning_v2"]:
            self.assertIn(key, models)
            tau_base = models[key]["tau_base"]
            tau_low = models[key]["tau_low"]
            tau_high = models[key]["tau_high"]
            self.assertLess(tau_low, tau_base, f"{key}: tau_low must be < tau_base")
            self.assertLess(tau_base, tau_high, f"{key}: tau_base must be < tau_high")

    def test_05_category_error_reporting(self):
        cat_csv = PROJECT_ROOT / "reports" / "phase11" / "category_error_analysis.csv"
        if not cat_csv.exists():
            self.skipTest("category_error_analysis.csv not yet generated by audit script")

        with open(cat_csv, "r", encoding="utf-8") as f:
            reader = list(csv.DictReader(f))

        expected_categories = {
            "appointment_account",
            "bank_otp",
            "delivery_tracking",
            "fake_jobs_loans_prizes",
            "hinglish_code_mixed",
            "kyc_account_blocking",
            "legitimate_promotional",
            "personal_conversation",
            "phishing_credential_theft",
            "telecom_service",
            "upi_transaction",
        }

        lora_v3_rows = [r for r in reader if r["model_key"] == "lora_v3"]
        found_categories = {r["category"] for r in lora_v3_rows}
        self.assertEqual(found_categories, expected_categories)

    def test_06_abstention_audit_reporting(self):
        abs_csv = PROJECT_ROOT / "reports" / "phase11" / "abstention_audit.csv"
        if not abs_csv.exists():
            self.skipTest("abstention_audit.csv not yet generated by audit script")

        with open(abs_csv, "r", encoding="utf-8") as f:
            reader = list(csv.DictReader(f))

        lora_rows = [r for r in reader if r["model_key"] == "lora_v3"]
        self.assertGreaterEqual(len(lora_rows), 2, "Expected test and benchmark rows for lora_v3")
        for r in lora_rows:
            coverage = float(r["coverage_rate"])
            self.assertGreaterEqual(coverage, 0.0)
            self.assertLessEqual(coverage, 1.0)

    def test_07_regression_fixture_remediation(self):
        # Verify lora_v3 passes both critical fixtures
        metrics_path = PROJECT_ROOT / "results" / "metrics" / "lora_v3.json"
        self.assertTrue(metrics_path.exists())
        with open(metrics_path, "r", encoding="utf-8") as f:
            metrics = json.load(f)

        upi_pred = metrics["evaluation_results"]["regression_fixtures"]["upi_bob"]["predicted_label"]
        jio_pred = metrics["evaluation_results"]["regression_fixtures"]["jio_reverification"]["predicted_label"]
        self.assertEqual(upi_pred, "HAM", "LoRA v3 must predict HAM on UPI BOB fixture")
        self.assertEqual(jio_pred, "HAM", "LoRA v3 must predict HAM on Jio Reverification fixture")

    def test_08_active_models_comparison_table_structure_and_splits(self):
        from app.metrics_loader import get_active_models_comparison_table

        table_rows = get_active_models_comparison_table(str(PROJECT_ROOT))
        self.assertEqual(len(table_rows), 3, "Comparison table must contain exactly 3 active models")

        expected_models = ["LoRA v3 (Default)", "DoRA v2", "Full Fine-Tuning v2"]
        found_models = [r["Model Strategy"] for r in table_rows]
        self.assertEqual(found_models, expected_models)

        # Check explicit metric headers
        required_headers = [
            "Model Strategy",
            "Role & Verification",
            "Architecture",
            "Weights Size",
            "Trainable Params",
            "Threshold (τ)",
            "Review Band",
            "UCI Test Acc (N=774)",
            "UCI Test Macro-F1",
            "UCI HAM Recall",
            "UCI SPAM Recall",
            "UCI Decided Acc",
            "UCI Coverage",
            "Curated Benchmark Acc (N=220)",
            "Curated Benchmark Macro-F1",
            "Benchmark HAM Recall",
            "Benchmark SPAM Recall",
            "Benchmark Decided Acc",
            "Benchmark Coverage",
            "Errors Averted (Abst.)",
            "BOB UPI Fixture",
            "Jio Rev Fixture",
        ]
        for row in table_rows:
            for header in required_headers:
                self.assertIn(header, row, f"Missing header '{header}' in table row")

        # Verify that splits are distinct and loaded accurately for lora_v3
        lora_row = table_rows[0]
        self.assertEqual(lora_row["UCI Test Acc (N=774)"], "97.03%")
        self.assertEqual(lora_row["UCI Test Macro-F1"], "93.19%")
        self.assertEqual(lora_row["UCI Decided Acc"], "97.28%")
        self.assertEqual(lora_row["UCI Coverage"], "99.61%")
        self.assertEqual(lora_row["Curated Benchmark Acc (N=220)"], "83.18%")
        self.assertEqual(lora_row["Curated Benchmark Macro-F1"], "83.10%")
        self.assertEqual(lora_row["Benchmark Decided Acc"], "86.00%")
        self.assertEqual(lora_row["Benchmark Coverage"], "90.91%")
        self.assertEqual(lora_row["Errors Averted (Abst.)"], "4 FP / 5 FN")
        self.assertEqual(lora_row["Weights Size"], "1.14 MB")

    def test_09_kpi_cards_and_benchmark_provenance(self):
        from app.metrics_loader import (
            get_active_models_kpi_cards,
            get_external_benchmark_provenance_summary,
        )

        kpis = get_active_models_kpi_cards(str(PROJECT_ROOT))
        self.assertIn("lora_v3", kpis)
        self.assertIn("dora_v2", kpis)
        self.assertIn("full_finetuning_v2", kpis)
        self.assertEqual(kpis["lora_v3"]["badge"], "PRODUCTION DEFAULT")
        self.assertEqual(kpis["lora_v3"]["benchmark_acc"], "83.18%")

        provenance = get_external_benchmark_provenance_summary(str(PROJECT_ROOT))
        self.assertEqual(len(provenance), 4, "Expected 4 provenance tiers for external benchmark")
        self.assertEqual(provenance[0]["Provenance Subset"], "Verified Real-World Subscriber SMS")
        self.assertEqual(provenance[0]["Sample Count"], 15)
        self.assertEqual(provenance[0]["Share of Benchmark"], "6.82% (15 / 220)")

    def test_10_missing_metric_keys_graceful_handling(self):
        from app.metrics_loader import _fmt_pct, _fmt_num, get_active_models_comparison_table

        self.assertEqual(_fmt_pct(None), "Unavailable")
        self.assertEqual(_fmt_pct("bad_type"), "Unavailable")
        self.assertEqual(_fmt_num(None), "Unavailable")
        self.assertEqual(_fmt_num("bad_type"), "Unavailable")

        # Passing an invalid path should not raise an unhandled exception and should populate Unavailable
        empty_table = get_active_models_comparison_table("non_existent_directory_for_test")
        self.assertEqual(len(empty_table), 3)
        for row in empty_table:
            self.assertEqual(row["UCI Test Acc (N=774)"], "Unavailable")
            self.assertEqual(row["Curated Benchmark Acc (N=220)"], "Unavailable")

    def test_11_unsupported_models_documentation_and_explicit_errors(self):
        from app.model_registry import (
            KNOWN_UNSUPPORTED_MODELS,
            get_model_spec,
        )

        # Ensure Phase 10 models have truthful documentation
        for m_id in ["full_finetuning_v3", "lora_v4", "dora_v3"]:
            self.assertIn(m_id, KNOWN_UNSUPPORTED_MODELS)
            doc = KNOWN_UNSUPPORTED_MODELS[m_id]
            self.assertNotIn("was not trained", doc.lower(), f"{m_id} error must not claim model was never trained")
            self.assertTrue(
                "validation-loss divergence" in doc.lower() or "regression" in doc.lower() or "overfitting" in doc.lower(),
                f"{m_id} error must explain technical reason for exclusion",
            )
            with self.assertRaises(ValueError) as ctx:
                get_model_spec(m_id)
            self.assertIn("experimental", str(ctx.exception).lower())


if __name__ == "__main__":
    unittest.main()

